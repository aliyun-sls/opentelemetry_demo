package org.example.config;

public class Config {
    public String checkoutAddr;
    public String productAddr;

    public String getCheckoutAddr() {
        return checkoutAddr;
    }

    public void setCheckoutAddr(String checkoutAddr) {
        this.checkoutAddr = checkoutAddr;
    }

    public String getProductAddr() {
        return productAddr;
    }

    public void setProductAddr(String productAddr) {
        this.productAddr = productAddr;
    }
}
